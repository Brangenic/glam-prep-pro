Hair, do not gamble

Oil in hair can turn into a whole week of stress. Keep it simple. Cornrows or tight braids, plus a fitted cap. Conditioner in the hair before the cap helps as a barrier.

How to get the oil off, without wrecking your skin

The goal is to lift oil first, then cleanse. If you rush to water, you spread it.

Step 1, wipe first. Use an old tee or towel to wipe off as much oil as possible before you shower.

Step 2, break it down. Use conditioner, baby oil, or an oil cleanser on the skin. Work it in, then wipe again.

Step 3, wash gently. Use a mild body wash, then repeat if you need to. If you have sensitive skin, keep it gentle, then moisturise properly after.

Step 4, moisturise. Your skin barrier has been through a lot. Put something soothing back on it.

