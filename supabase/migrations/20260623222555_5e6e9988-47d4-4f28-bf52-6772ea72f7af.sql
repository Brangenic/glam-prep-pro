## 💰 What to Budget for Trinidad Carnival

Costume (frontline or backline): between US$500 and US$2,500

Fete tickets: range from US$50 to US$700 per event

Flights: generally US$500 to US$1,200 depending on location

Hotels or Airbnbs: between US$200 and US$600 per night

Glam Hub: professional Carnival makeup starts from US$160 — see the [Carnival makeup service page](https://www.carnivalglamhub.com/services/carnival-makeup) for the full breakdown of looks, add-ons and what's included.

💡 **Pro Tips:**

- _Exchange rate: US$1 to roughly TT$7. Change US$300 at the cambio when you land_

- _Purchase all fete tickets in advance online: download the Island E Ticket app_

- _Fetes to purchase early: SOAKA, Private Ryan's Soca Brain Wash, Pinknic, Sunnation Breakfast Party, Nectar, Citrus, Travis World, and Vibe_

- _TTRS (Trinidad's Uber) is cheaper than hiring a driver_

